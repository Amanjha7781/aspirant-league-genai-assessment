from __future__ import annotations

import asyncio
import json
from pathlib import Path

from extraction_app.extractor import extract_invoice
from extraction_app.pdf import extract_pdf_text
from extraction_app.validation import validate_candidate
from shared.llm import LLMClient, ModelUnavailable


ROOT = Path(__file__).resolve().parents[2]
SAMPLE_DIR = ROOT / "samples" / "extraction"
OUT_DIR = ROOT / "evaluation" / "extraction"
FIELDS = ("invoice_id", "invoice_date", "vendor", "currency", "subtotal", "tax", "total")


async def evaluate() -> dict:
    labels = json.loads((SAMPLE_DIR / "ground_truth.json").read_text("utf-8"))["documents"]
    client = LLMClient()
    output = {"dataset": "synthetic invoices generated by samples/extraction/generate_samples.py", "documents_expected": len(labels), "model_configured": client.configured, "field_count": len(labels) * len(FIELDS), "schema_validity_rate": "BLOCKED - no model output to validate", "field_exact_match_accuracy": "BLOCKED - requires model output", "expected_present_value_accuracy": "BLOCKED - requires model output", "per_document": []}
    if not client.configured:
        output["status"] = "BLOCKED"
        output["reason"] = "No authorized LLM endpoint is configured. No mock or heuristic output is scored as model extraction."
        return output
    schema_valid = 0
    exact_correct = 0
    present_correct = 0
    present_denominator = sum(label["expected"][name]["status"] == "found" for label in labels for name in FIELDS)
    error_count = 0
    for label in labels:
        content = (SAMPLE_DIR / label["file"]).read_bytes()
        text, _pages = extract_pdf_text(content)
        row = {"file": label["file"], "fields": {}}
        try:
            candidate = await extract_invoice(client, text)
            schema_valid += 1
            candidate, _checks, warnings = validate_candidate(candidate, text)
            row["warnings"] = warnings
            for name in FIELDS:
                expected = label["expected"][name]
                actual = getattr(candidate, name)
                exact = actual.status == expected["status"] and actual.normalized_value == expected["normalized_value"]
                exact_correct += int(exact)
                if expected["status"] == "found":
                    present_denominator += 1
                    present_correct += int(actual.status == "found" and actual.normalized_value == expected["normalized_value"])
                row["fields"][name] = {"status": actual.status, "normalized_value": actual.normalized_value, "expected": expected, "exact_match": exact}
        except ModelUnavailable as exc:
            row["error"] = str(exc)
            error_count += 1
            for name in FIELDS:
                row["fields"][name] = {"status": "missing", "normalized_value": None, "expected": label["expected"][name], "exact_match": False}
        output["per_document"].append(row)
    output["status"] = "COMPLETE" if error_count == 0 else "PARTIAL"
    output["schema_validity_rate"] = round(schema_valid / len(labels), 4)
    output["field_exact_match_accuracy"] = round(exact_correct / output["field_count"], 4)
    output["expected_present_value_accuracy"] = round(present_correct / max(present_denominator, 1), 4)
    output["denominators"] = {"schema_validity_rate": "successfully schema-validated document outputs / 10 documents", "field_exact_match_accuracy": "exact status and normalized-value matches / 70 annotated fields; missing and ambiguous statuses are included; failed documents count as incorrect", "expected_present_value_accuracy": "correct found normalized values / all fields labeled found in ground truth; model-missing values and failed documents count incorrect"}
    return output


def main() -> None:
    result = asyncio.run(evaluate())
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "raw_results.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({key: result[key] for key in ("status", "documents_expected", "schema_validity_rate", "field_exact_match_accuracy", "expected_present_value_accuracy") if key in result} | {"output": "evaluation/extraction/raw_results.json"}, indent=2))


if __name__ == "__main__":
    main()
